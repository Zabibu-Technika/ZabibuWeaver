// Vendor the Canary judging engine into Weaver.
//
// Why vendored, rather than importing a sibling checkout: Weaver has to run on its
// own. A path to `../zabibu-canary/packages/engine` is a build-time dependency on
// where a second project happens to live on one machine, and it silently vanishes
// the moment Weaver is cloned anywhere else. Importing the sibling is not
// integration; it is co-location.
//
// Why pinned and hashed, rather than "just copy the files": the entire claim is
// that the judgement is independent, deterministic, and checkable. A copy nobody
// can verify against its source is just a fork wearing a costume. So:
//
//   * the files are copied BYTE-FOR-BYTE and never edited afterwards. Not even a
//     header comment — that would change the hash, and the hash is the point.
//   * `provenance.json` records the upstream commit and the sha256 of every file.
//   * `src/engine/provenance.test.ts` recomputes those hashes on every test run.
//
// The signing half of Canary (`ledger.ts`) is deliberately NOT vendored. Weaver
// embeds the judge, not the pen: the agent can be judged, but it must not be able
// to sign its own permission slip.
//
//   node scripts/vendor-engine.mjs [--from <engine-src-dir>]
//   npm run vendor:engine
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// The closure Weaver actually needs. `ledger.ts` and `demo-diff.ts` are excluded
// on purpose — see the note above.
const VENDORED = ["analyze.ts", "impact.ts", "plain.ts"];

const here = dirname(fileURLToPath(import.meta.url));
const destination = join(here, "..", "src", "engine");

const argIndex = process.argv.indexOf("--from");
const explicit = argIndex === -1 ? process.env.WEAVER_ENGINE_SRC : process.argv[argIndex + 1];

// Default to the sibling checkout, which is where the engine lives during
// development. Override with --from or WEAVER_ENGINE_SRC.
const source = resolve(
  explicit ?? join(here, "..", "..", "zabibu-canary", "packages", "engine", "src"),
);

function fail(message) {
  console.error(`vendor-engine: ${message}`);
  process.exit(1);
}

if (!existsSync(source)) {
  fail(
    `no engine source at ${source}\n` +
      `  point at one with: node scripts/vendor-engine.mjs --from <dir>`,
  );
}

function sha256(file) {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

function git(cwd, args) {
  try {
    return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return null;
  }
}

// The commit the engine came from, if it came from a git checkout. Recorded so a
// reader can diff the vendored copy against that exact revision.
const repoRoot = git(source, ["rev-parse", "--show-toplevel"]);
const commit = repoRoot === null ? null : git(repoRoot, ["rev-parse", "HEAD"]);
const dirty =
  repoRoot === null ? null : (git(repoRoot, ["status", "--porcelain"]) ?? "").length > 0;

mkdirSync(destination, { recursive: true });

const files = {};
for (const name of VENDORED) {
  const from = join(source, name);
  if (!existsSync(from)) fail(`upstream is missing ${name} (looked in ${source})`);

  const bytes = readFileSync(from);
  // Byte-for-byte. If this is not a plain copy the provenance is a lie.
  writeFileSync(join(destination, name), bytes);

  files[name] = { sha256: sha256(from), bytes: bytes.length };
  console.log(`  vendored  ${name.padEnd(12)} ${files[name].sha256.slice(0, 12)}  ${bytes.length} bytes`);
}

const provenance = {
  $comment:
    "Generated by scripts/vendor-engine.mjs — do not edit by hand. The vendored " +
    "files are byte-identical copies; provenance.test.ts verifies the hashes.",
  source: {
    // Deliberately portable: no absolute paths. The test and the re-vendor script
    // both find a sibling checkout by convention, or via WEAVER_ENGINE_SRC.
    engineDir: "packages/engine/src",
    commit,
    // A dirty upstream means the commit does not fully describe what was copied.
    // The per-file hashes below still pin the content exactly.
    dirty,
  },
  files,
};

writeFileSync(join(destination, "provenance.json"), `${JSON.stringify(provenance, null, 2)}\n`);

console.log(
  `vendor-engine: wrote ${VENDORED.length} files + provenance.json to src/engine` +
    (commit === null ? "" : ` (upstream ${commit.slice(0, 8)}${dirty ? ", dirty" : ""})`),
);
if (dirty) {
  console.warn(
    "vendor-engine: warning — the upstream engine had uncommitted changes, so the\n" +
      "  recorded commit does not fully describe what was vendored. Commit upstream\n" +
      "  and re-run for a provenance record that means something.",
  );
}
